def get_flowchart_extract_prompt(overview_section: str) -> str:
    """Miro用: マニュアルの全体像セクションからフローチャート構造を抽出するプロンプト"""
    return f"""以下のマニュアルの「全体像」セクションから、業務フローチャートの構造をJSON形式で抽出してください。

## 出力形式（JSON）

```json
{{
  "title": "フローチャートのタイトル",
  "phases": [
    {{
      "name": "フェーズ名（例: 事前準備）",
      "steps": [
        {{
          "id": "s1",
          "type": "start",
          "label": "開始",
          "role": ""
        }},
        {{
          "id": "s2",
          "type": "process",
          "label": "企画シートを作成する",
          "role": "企画担当者",
          "deadline": "前日18:00"
        }},
        {{
          "id": "s3",
          "type": "decision",
          "label": "リーダー承認？",
          "role": "リーダー"
        }},
        {{
          "id": "s4",
          "type": "end",
          "label": "完了",
          "role": ""
        }}
      ],
      "connections": [
        {{"from": "s1", "to": "s2"}},
        {{"from": "s2", "to": "s3"}},
        {{"from": "s3", "to": "s4", "label": "YES"}},
        {{"from": "s3", "to": "s2", "label": "NO"}}
      ]
    }}
  ]
}}
```

## typeの種類
- "start": 開始ノード
- "process": 処理ステップ
- "decision": 判断・分岐
- "end": 終了ノード

## 注意事項
- Mermaid図がある場合はそれを元に構造化する
- テキストのフロー記述からも抽出する
- idは "s" + 連番（フェーズごとにリセット: p1_s1, p1_s2, p2_s1...）
- 各ステップに担当者（role）がある場合は含める
- JSONのみを出力し、説明文は不要

## 全体像セクション

{overview_section}"""

def get_draft_prompt(structured_data: str) -> str:
    """Step2: 構造化データからマニュアル草稿を生成するプロンプト"""
    return f"""以下の構造化データを元に、マニュアルを生成してください。

## 出力ルール（厳守）
- Notion互換のMarkdownで出力する
- コードブロック（```）で囲まない
- HTMLタグは使わない
- コールアウトは引用記法と絵文字で表現（例: > 💡 ポイント）
- 重要なキーワードは**太字**で強調する

## 必須7項目（すべて含めること）

### 【0】目次
- マニュアル全体の構成を箇条書きで

### 【1】目的・対象者・ゴール
- **目的**: なぜこのマニュアルが存在するか
- **対象者**: 使用者の役割を明示
- **ゴール（行動基準型）**: 「○○を△分以内に完了できる」など具体的に
  - 目安時間を必ず含める

### 【2】行動基準（あり方）
- 業務に臨む姿勢・マインドセット
- > 💡 の引用形式で記載

### 【3】全体像
- 業務フローを**Mermaid形式**で記載（```mermaid で囲む）
- フェーズ別にフローチャートを作成
- 関連リソース・ツールのリンク一覧

### 【4】詳細手順
- フェーズ別に記載
- 各ステップは番号付きリストで
- 「誰が・いつまでに・何を・どこで」を明確に
- 締切は `コード書式` + 太字で表記
- 担当者は `コード書式` + 太字で表記
- Slack・リソースは `コード書式` + リンク付きで表記
- チャット文はコードブロックで表記
- アナウンスは > 📣 のコールアウト形式で表記

### 【5】判断ポイント・イレギュラー対応
- 判断が必要な場面とその基準
- イレギュラーケースと対応方法
- エスカレーション先
- > 📌 のコールアウト形式で表記

### 【6】補足（トラブル対応・参考情報）
- よくあるトラブルと対処法
- 参考資料・関連マニュアルへのリンク

### 【7】表記ルール・更新履歴
- 用語統一表（あれば）
- 文末は「〜する。」で統一
- 更新履歴テーブル: | 日付 | 更新者 | 更新内容 | 理由 |

## 構造化データ

{structured_data}"""


